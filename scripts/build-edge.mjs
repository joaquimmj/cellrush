#!/usr/bin/env node
// Bundles packages/drills (+ engine) into one ESM file for the Supabase Edge Function, so the
// server replays runs with exactly the code the browser runs. Output is generated: not committed.
import { build } from "esbuild";

await build({
  entryPoints: ["packages/drills/src/index.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: "supabase/functions/_shared/cellrush.gen.js",
  banner: { js: "// GENERATED by scripts/build-edge.mjs from packages/drills — do not edit.\n" },
  logLevel: "info",
});
