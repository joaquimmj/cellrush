#!/usr/bin/env node
// Writes apps/web/.env.local from the running local Supabase stack (`pnpm db:start` first).
// Only the public URL + anon key go to the web app. The file is gitignored.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const out = execSync("npx supabase status -o env", { encoding: "utf8" });
const env = Object.fromEntries(
  out.split("\n").map((l) => /^([A-Z_]+)="?(.*?)"?$/.exec(l.trim())).filter(Boolean).map((m) => [m[1], m[2]]),
);
if (!env.API_URL || !env.ANON_KEY) throw new Error("local Supabase is not running: run `pnpm db:start`");
writeFileSync(
  "apps/web/.env.local",
  `# generated by scripts/env-local.mjs: local Supabase only\nVITE_SUPABASE_URL=${env.API_URL}\nVITE_SUPABASE_ANON_KEY=${env.ANON_KEY}\n`,
);
console.log(`apps/web/.env.local → ${env.API_URL} (mail: ${env.INBUCKET_URL ?? env.MAILPIT_URL ?? "see supabase status"})`);
